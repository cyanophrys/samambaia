const DB_NAME = 'SamambaiaDB';
const DB_VERSION = 1;

let db;

export function initDB() {
  return new Promise((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, DB_VERSION);

    request.onerror = () => reject(request.error);

    request.onsuccess = () => {
      db = request.result;

      db.onversionchange = () => {
        db.close();
        db = undefined;
      };

      resolve(db);
    };

    request.onupgradeneeded = () => {
    };
  });
}
